def test_migration_007_protects_events_and_function_permissions(
    postgres_database: DatabaseFactory,
) -> None:
    """Translation events reject direct writes and retain the statistics function ACL."""
    seed_sql = """
        INSERT INTO public.word (id, date_changed, word, language)
        VALUES (1, statement_timestamp() - interval '30 days', 'old', 'en');
    """
    with postgres_database(7, seed_sql) as database:
        with database.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO public.definitions (id, definition, definition_language)
                VALUES (1, 'dikanteny', 'mg');
                INSERT INTO public.dictionary (word, definition) VALUES (1, 1);
                """
            )
            direct_writes = [
                """
                INSERT INTO public.events_malagasy_translation_created
                    (word_id, definition_id, source_language, cause)
                VALUES (99, 99, 'en', 'dictionary_insert')
                """,
                "UPDATE public.events_malagasy_translation_created SET source_language = 'fr' WHERE word_id = 1",
                "DELETE FROM public.events_malagasy_translation_created WHERE word_id = 1",
            ]
            for statement in direct_writes:
                with pytest.raises(psycopg2.Error) as error:
                    cursor.execute(statement)
                assert error.value.pgcode == "42501"

            cursor.execute("SELECT count(*) FROM public.events_malagasy_translation_created")
            assert cursor.fetchone()[0] == 1
        _assert_statistics_permissions(database)


