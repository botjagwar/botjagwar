DatabaseFactory = Callable[[int, str], AbstractContextManager[connection]]


def _postgres_unavailable(reason: str) -> NoReturn:
    """Skip unavailable local PostgreSQL or fail when CI requires it."""
    if os.getenv("BOTJAGWAR_REQUIRE_POSTGRES_TESTS") == "1":
        pytest.fail(reason)
    pytest.skip(reason)


@pytest.fixture(scope="module")
def postgres_database() -> Iterator[DatabaseFactory]:
    """Provide isolated temporary databases containing migrations through a requested version."""
    admin_dsn = os.getenv("BOTJAGWAR_TEST_POSTGRES_DSN", "dbname=postgres")
    try:
        admin_connection = psycopg2.connect(admin_dsn)
    except psycopg2.Error as error:
        _postgres_unavailable(f"PostgreSQL connection unavailable: {error}")

    admin_connection.autocommit = True
    created_role = False
    database_names: set[str] = set()
    try:
        with admin_connection.cursor() as cursor:
            cursor.execute("SELECT 1 FROM pg_roles WHERE rolname = 'botjagwar'")
            if cursor.fetchone() is None:
                try:
                    cursor.execute("CREATE ROLE botjagwar NOLOGIN")
                    created_role = True
                except psycopg2.Error as error:
                    _postgres_unavailable(f"PostgreSQL role creation unavailable: {error}")

        @contextmanager
        def create_database(last_migration: int, seed_sql: str = "") -> Iterator[connection]:
            """Create, migrate, and reliably remove one test database."""
            database_name = f"botjagwar_test_{uuid.uuid4().hex}"
            try:
                with admin_connection.cursor() as cursor:
                    cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name)))
            except psycopg2.Error as error:
                _postgres_unavailable(f"PostgreSQL database creation unavailable: {error}")

            database_names.add(database_name)
            test_dsn = psycopg2.extensions.make_dsn(admin_dsn, dbname=database_name)
            test_connection = psycopg2.connect(test_dsn)
            test_connection.autocommit = True
            try:
                with test_connection.cursor() as cursor:
                    cursor.execute(BASE_SCHEMA)
                    if seed_sql:
                        cursor.execute(seed_sql)
                    for version in range(6, last_migration + 1):
                        cursor.execute(MIGRATIONS[version].read_text(encoding="utf-8"))
                yield test_connection
            finally:
                test_connection.close()
                with admin_connection.cursor() as cursor:
                    cursor.execute(
                        sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(database_name))
                    )
                database_names.discard(database_name)

        yield create_database
    finally:
        for database_name in database_names:
            with admin_connection.cursor() as cursor:
                cursor.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(database_name)))
        if created_role:
            with admin_connection.cursor() as cursor:
                cursor.execute("DROP ROLE IF EXISTS botjagwar")
        admin_connection.close()


def _assert_statistics_permissions(database: connection) -> None:
    """Assert the statistics function ACL has no PUBLIC execute and grants botjagwar execute."""
    with database.cursor() as cursor:
        cursor.execute(
            """
            SELECT
                COALESCE(bool_or(acl.grantee = 0 AND acl.privilege_type = 'EXECUTE'), false),
                COALESCE(bool_or(acl.grantee = roles.oid AND acl.privilege_type = 'EXECUTE'), false)
            FROM pg_proc AS functions
            JOIN pg_namespace AS schemas ON schemas.oid = functions.pronamespace
            CROSS JOIN pg_roles AS roles
            LEFT JOIN LATERAL aclexplode(
                COALESCE(functions.proacl, acldefault('f', functions.proowner))
            ) AS acl ON true
            WHERE schemas.nspname = 'public'
              AND functions.proname = 'atlas_dashboard_statistics'
              AND pg_get_function_identity_arguments(functions.oid) = 'p_language_limit integer'
              AND roles.rolname = 'botjagwar'
            GROUP BY roles.oid
            """
        )
        assert cursor.fetchone() == (False, True)


def _statistics_row(database: connection, period: str) -> tuple[int, list[dict[str, object]]]:
    """Return entry and translation counts for one statistics period."""
    with database.cursor() as cursor:
        cursor.execute(
            """
            SELECT entry_count, translated_languages
            FROM public.atlas_dashboard_statistics()
            WHERE period = %s
            """,
            (period,),
        )
        row = cursor.fetchone()
    assert row is not None
    return row


def test_migration_006_returns_six_utc_periods_and_restricted_permissions(
    postgres_database: DatabaseFactory,
) -> None:
    """Migration 006 exposes six UTC-derived periods through a restricted function."""
    with postgres_database(6, "") as database:
        with database.cursor() as cursor:
            cursor.execute("SET TIME ZONE 'Pacific/Auckland'")
            cursor.execute(
                """
                SELECT period, period_start, period_end, generated_at
                FROM public.atlas_dashboard_statistics()
                """
            )
            rows = cursor.fetchall()

        assert [row[0] for row in rows] == [
            "last_day",
            "last_7_days",
            "last_week",
            "last_month",
            "year_to_date",
            "last_year",
        ]
        generated_at = rows[0][3].astimezone(timezone.utc)
        periods = {
            period: (start.astimezone(timezone.utc), end.astimezone(timezone.utc))
            for period, start, end, _generated_at in rows
        }
        assert all(row[3].astimezone(timezone.utc) == generated_at for row in rows)
        assert periods["last_day"] == (generated_at - timedelta(days=1), generated_at)
        assert periods["last_7_days"] == (generated_at - timedelta(days=7), generated_at)
        last_week_start, last_week_end = periods["last_week"]
        assert last_week_end.weekday() == 0
        assert last_week_end.time() == datetime.min.time()
        assert last_week_end - last_week_start == timedelta(days=7)
        last_month_start, last_month_end = periods["last_month"]
        assert last_month_start.day == last_month_end.day == 1
        assert last_month_start.time() == last_month_end.time() == datetime.min.time()
        year_to_date_start, year_to_date_end = periods["year_to_date"]
        assert (year_to_date_start.month, year_to_date_start.day, year_to_date_start.hour) == (1, 1, 0)
        assert year_to_date_end == generated_at
        last_year_start, last_year_end = periods["last_year"]
        assert (last_year_start.month, last_year_start.day, last_year_start.hour) == (1, 1, 0)
        assert last_year_end.year == last_year_start.year + 1
        _assert_statistics_permissions(database)


def test_migration_007_generates_immutable_created_at_and_preserves_legacy_rows(
    postgres_database: DatabaseFactory,
) -> None:
    """Migration 007 avoids legacy rewrites and owns all new creation times."""
    seed_sql = """
        INSERT INTO public.word (id, date_changed, word, language) VALUES
            (1, TIMESTAMPTZ '2020-03-04 05:06:07+00', 'known', 'en'),
            (2, NULL, 'unknown', 'fr');
    """
    with postgres_database(7, seed_sql) as database:
        with database.cursor() as cursor:
            cursor.execute("SELECT id, created_at FROM public.word ORDER BY id")
            legacy_rows = cursor.fetchall()
            assert legacy_rows == [(1, None), (2, None)]

            entry_count, _translated_languages = _statistics_row(database, "last_year")
            assert entry_count == 0

            cursor.execute(
                """
                INSERT INTO public.word (id, date_changed, created_at, word, language)
                VALUES (3, now(), TIMESTAMPTZ '2000-01-01 00:00:00+00', 'new', 'de')
                RETURNING created_at, statement_timestamp()
                """
            )
            created_at, statement_time = cursor.fetchone()
            assert created_at == statement_time

            with pytest.raises(psycopg2.Error) as error:
                cursor.execute("UPDATE public.word SET created_at = TIMESTAMPTZ '2001-01-01 00:00:00+00' WHERE id = 3")
            assert error.value.pgcode == "22000"

            cursor.execute("SELECT created_at FROM public.word WHERE id = 3")
            assert cursor.fetchone()[0] == created_at


