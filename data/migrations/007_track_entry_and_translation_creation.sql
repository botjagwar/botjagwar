CREATE OR REPLACE FUNCTION public.enforce_word_created_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $function$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.created_at := statement_timestamp();
    ELSIF NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'word.created_at is immutable'
            USING ERRCODE = '22000';
    END IF;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER enforce_word_created_at
BEFORE INSERT OR UPDATE OF created_at ON public.word
FOR EACH ROW
EXECUTE FUNCTION public.enforce_word_created_at();

CREATE INDEX IF NOT EXISTS idx_word_created_at
    ON public.word (created_at)
    WHERE created_at IS NOT NULL;

