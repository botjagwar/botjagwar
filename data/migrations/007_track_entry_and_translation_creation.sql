CREATE OR REPLACE FUNCTION public.capture_malagasy_translation_link()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    source_language character varying(10);
    target_language character varying(6);
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW.word IS NOT DISTINCT FROM OLD.word
       AND NEW.definition IS NOT DISTINCT FROM OLD.definition THEN
        RETURN NEW;
    END IF;

    SELECT words.language, definitions.definition_language
    INTO source_language, target_language
    FROM public.word AS words
    CROSS JOIN public.definitions AS definitions
    WHERE words.id = NEW.word
      AND definitions.id = NEW.definition;

    IF source_language <> 'mg' AND target_language = 'mg' THEN
        INSERT INTO public.events_malagasy_translation_created (
            word_id,
            definition_id,
            source_language,
            created_at,
            cause
        ) VALUES (
            NEW.word,
            NEW.definition,
            source_language,
            statement_timestamp(),
            CASE WHEN TG_OP = 'INSERT' THEN 'dictionary_insert' ELSE 'dictionary_update' END
        );
    END IF;
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS capture_malagasy_translation_link ON public.dictionary;
CREATE TRIGGER capture_malagasy_translation_link
AFTER INSERT OR UPDATE OF word, definition ON public.dictionary
FOR EACH ROW
EXECUTE FUNCTION public.capture_malagasy_translation_link();

CREATE OR REPLACE FUNCTION public.capture_reclassified_malagasy_definition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
BEGIN
    IF NEW.definition_language = 'mg'
       AND OLD.definition_language IS DISTINCT FROM 'mg' THEN
        INSERT INTO public.events_malagasy_translation_created (
            word_id,
            definition_id,
            source_language,
            created_at,
            cause
        )
        SELECT
            links.word,
            NEW.id,
            words.language,
            statement_timestamp(),
            'definition_reclassified'
        FROM public.dictionary AS links
        JOIN public.word AS words ON words.id = links.word
        WHERE links.definition = NEW.id
          AND words.language <> 'mg';
    END IF;
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS capture_reclassified_malagasy_definition ON public.definitions;
CREATE TRIGGER capture_reclassified_malagasy_definition
AFTER UPDATE OF definition_language ON public.definitions
FOR EACH ROW
EXECUTE FUNCTION public.capture_reclassified_malagasy_definition();

CREATE OR REPLACE FUNCTION public.protect_malagasy_translation_events()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $function$
BEGIN
    IF TG_OP = 'INSERT' AND pg_trigger_depth() > 1 THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Malagasy translation events are append-only and trigger-managed'
        USING ERRCODE = '42501';
END;
$function$;

CREATE TRIGGER protect_malagasy_translation_events
BEFORE INSERT OR UPDATE OR DELETE ON public.events_malagasy_translation_created
FOR EACH ROW
EXECUTE FUNCTION public.protect_malagasy_translation_events();

CREATE TRIGGER protect_malagasy_translation_events_truncate
BEFORE TRUNCATE ON public.events_malagasy_translation_created
FOR EACH STATEMENT
EXECUTE FUNCTION public.protect_malagasy_translation_events();

